def _manifest(scan_id: str) -> ScanManifest:
    return ScanManifest(scan_id, "repo", None, "main", "0" * 40, "python-adapter/0.1.0", "2026-06-13T00:00:00+00:00", "Level1SemanticAnalysisReduced", "FailedOrPartial", [], [], ["python"], [])


def _package_facts(facts):
    return [fact for fact in facts if fact.fact_type == "PackageReferenced"]


def _gap_facts(facts):
    return [fact for fact in facts if fact.fact_type == "AnalysisGap"]


def _by_name(facts, name):
    return [fact for fact in _package_facts(facts) if fact.properties["packageName"] == name]


def test_uv_lock_emits_resolved_versions_with_proven_direct_and_transitive(tmp_path: Path) -> None:
    lock = tmp_path / "uv.lock"
    lock.write_text(UV_LOCK, encoding="utf-8")
    gaps: list[str] = []

    facts = read_lockfiles(tmp_path, _manifest("uv"), [lock], [], gaps)

    packages = _package_facts(facts)
    assert {fact.properties["packageName"] for fact in packages} == {"requests", "urllib3", "flask"}
    requests = _by_name(facts, "requests")[0]
    assert requests.properties["resolvedVersion"] == "2.32.3"
    assert requests.properties["version"] == "2.32.3"
    assert requests.properties["ecosystem"] == "python"
    assert requests.properties["sourceKind"] == "lockfile"
    assert requests.properties["manifestKind"] == "uv.lock"
    assert requests.properties["packageManager"] == "uv"
    assert requests.properties["lockfilePath"] == "uv.lock"
    assert len(requests.properties["lockfileHash"]) == 32
    assert requests.properties["registryOrigin"] == "pypi.org"
    assert requests.properties["dependencyRelation"] == "direct"
    assert _by_name(facts, "urllib3")[0].properties["dependencyRelation"] == "transitive"
    assert requests.evidence.extractor_id == "PythonLockfileExtractor"
    assert requests.evidence.extractor_version == "python-lockfile/0.1.0"
    assert requests.evidence.file_path == "uv.lock"
    assert requests.evidence.start_line == 19  # the [[package]] header line of the requests entry
    assert gaps == []


