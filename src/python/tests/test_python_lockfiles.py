def test_scan_emits_pipfile_unsupported_metadata_gap_and_lockfile_facts(tmp_path: Path) -> None:
    (tmp_path / "pyproject.toml").write_text(PYPROJECT, encoding="utf-8")
    (tmp_path / "uv.lock").write_text(UV_LOCK, encoding="utf-8")
    (tmp_path / "Pipfile").write_text("[packages]\nrequests = \"*\"\n", encoding="utf-8")
    (tmp_path / "app.py").write_text("import requests\n", encoding="utf-8")
    _git(tmp_path, "init")
    _git(tmp_path, "config", "user.email", "scan@example.invalid")
    _git(tmp_path, "config", "user.name", "scan")
    _git(tmp_path, "add", "-A")
    _git(tmp_path, "commit", "-m", "fixture")
    out = tmp_path / "scan-out"

    manifest, facts = scan(make_options(str(tmp_path), str(out)))

    gap_kinds = [fact.properties.get("gapKind") for fact in facts if fact.fact_type == "AnalysisGap"]
    assert "unsupported-metadata" in gap_kinds
    pipfile_gap = next(fact for fact in facts if fact.properties.get("gapKind") == "unsupported-metadata")
    assert pipfile_gap.rule_id == "python.package.metadata.v1"
    assert pipfile_gap.evidence.file_path == "Pipfile"
    lockfile_rows = [fact for fact in facts if fact.fact_type == "PackageReferenced" and fact.properties.get("sourceKind") == "lockfile"]
    assert {fact.properties["packageName"] for fact in lockfile_rows} == {"requests", "urllib3", "flask"}
    pipfile_packages = [fact for fact in lockfile_rows if fact.evidence.file_path == "Pipfile"]
    assert pipfile_packages == []
    ndjson = (out / "facts.ndjson").read_text(encoding="utf-8").splitlines()
    assert any('"gapKind":"unsupported-metadata"' in line for line in ndjson)
    assert any('"resolvedVersion":"2.32.3"' in line for line in ndjson)
    assert manifest.projects == ["Pipfile", "pyproject.toml"]


def _git(repo: Path, *arguments: str) -> None:
    subprocess.run(["git", *arguments], cwd=repo, check=True, capture_output=True, text=True)
