using System.Runtime.CompilerServices;
using Microsoft.CodeAnalysis;

namespace TraceMap.Core;

/// <summary>One compilation document: its repo-relative path, or the typed gap that keeps it out of helper caller evidence.</summary>
internal sealed record SqlServerCompilationDocument(string? Path, string? Gap);

/// <summary>
/// The documents of one project compilation as the scanning adapter saw them. Only ordinary project documents inside the
/// project directory and the repository have a path; generated, linked, external and path-unsafe documents carry a gap.
/// </summary>
internal sealed class SqlServerCompilationScope
{
    internal const int MaxTrees = 1024;
    internal const int MaxCharacters = 8 * 1024 * 1024;
    internal const string GeneratedGap = "helper-generated-document-unsupported";
    internal const string LinkedGap = "helper-linked-document-unsupported";
    internal const string PathGap = "helper-document-path-unsupported";
    private readonly IReadOnlyDictionary<string, SqlServerCompilationDocument> documents;
    private readonly Lazy<bool> errors;

    internal SqlServerCompilationScope(IReadOnlyDictionary<string, SqlServerCompilationDocument> documents, bool reduced, Compilation compilation)
    {
        this.documents = documents;
        Reduced = reduced;
        // Evaluated once and only when an internal helper reaches this check; unresolved binding could hide a call.
        errors = new(() => compilation.GetDiagnostics().Any(d => d.Severity == DiagnosticSeverity.Error), LazyThreadSafetyMode.ExecutionAndPublication);
    }

    /// <summary>Scan-scope exclusion removed documents of this project before compilation.</summary>
    internal bool Reduced { get; }
    internal bool HasErrors => errors.Value;

    /// <summary>The tree's document class; trees that are not project documents (source generators, injected trees) are generated.</summary>
    internal SqlServerCompilationDocument Document(SyntaxTree tree)
    {
        if (string.IsNullOrEmpty(tree.FilePath) || !documents.TryGetValue(tree.FilePath, out var document)) return new(null, GeneratedGap);
        if (document.Gap is not null) return document;
        var text = tree.GetText();
        var prefix = text.ToString(new Microsoft.CodeAnalysis.Text.TextSpan(0, Math.Min(text.Length, 512)));
        return prefix.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase) || prefix.Contains("<autogenerated", StringComparison.OrdinalIgnoreCase)
            ? new(null, GeneratedGap) : document;
    }
}

/// <summary>
/// Per-compilation document scopes registered by the C# and VB semantic adapters, keyed weakly by the compilation the Fill's
/// semantic model belongs to. A compilation without a registered scope (explicit-context scans, direct API callers) has no
/// whole-compilation caller evidence.
/// </summary>
internal static class SqlServerCompilationScopes
{
    private static readonly ConditionalWeakTable<Compilation, SqlServerCompilationScope> Scopes = new();
    private static readonly ConditionalWeakTable<Solution, HashSet<ProjectId>> ReducedProjects = new();
    private static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".g.vb", ".g.i.vb", ".generated.cs", ".generated.vb", ".designer.cs",
        ".designer.vb", ".AssemblyInfo.cs", ".AssemblyInfo.vb", ".AssemblyAttributes.cs", ".AssemblyAttributes.vb"];

    /// <summary>Records that scan-scope exclusion removed documents of these projects from <paramref name="solution"/>.</summary>
    internal static void MarkReduced(Solution solution, IEnumerable<ProjectId> projects)
    {
        var set = ReducedProjects.GetValue(solution, _ => []);
        lock (set) set.UnionWith(projects);
    }

    internal static SqlServerCompilationScope? Find(Compilation? compilation)
        => compilation is not null && Scopes.TryGetValue(compilation, out var scope) ? scope : null;

    /// <summary>Registers the document scope of <paramref name="project"/>'s <paramref name="compilation"/>.</summary>
    internal static void Register(string repoPath, Project project, Compilation compilation)
    {
        if (string.IsNullOrWhiteSpace(project.FilePath) || Path.GetDirectoryName(project.FilePath) is not { Length: > 0 } directory) return;
        var projectDirectory = CSharpSemanticExtractor.ToRelativePathProjection(repoPath, directory);
        var documents = new Dictionary<string, SqlServerCompilationDocument>(StringComparer.Ordinal);
        foreach (var document in project.Documents)
        {
            if (document.FilePath is not { Length: > 0 } fullPath) continue;
            var entry = Classify(repoPath, projectDirectory, fullPath);
            // A file listed twice is compiled as two documents; neither is an ordinary single document.
            if (!documents.TryAdd(fullPath, entry)) documents[fullPath] = new(null, SqlServerCompilationScope.LinkedGap);
        }
        bool reduced;
        if (ReducedProjects.TryGetValue(project.Solution, out var set)) lock (set) reduced = set.Contains(project.Id);
        else reduced = false;
        Scopes.AddOrUpdate(compilation, new(documents, reduced, compilation));
    }

    private static SqlServerCompilationDocument Classify(string repoPath, CSharpSemanticExtractor.RelativePathProjection projectDirectory, string fullPath)
    {
        var name = Path.GetFileName(fullPath);
        if (GeneratedSuffixes.Any(s => name.EndsWith(s, StringComparison.OrdinalIgnoreCase))) return new(null, SqlServerCompilationScope.GeneratedGap);
        var projection = CSharpSemanticExtractor.ToRelativePathProjection(repoPath, fullPath);
        // Outside the repository, or outside the project directory (MSBuild Link or ".." includes): possibly shared by other compilations.
        if (projection.IsExternal || projectDirectory.IsExternal
            || projectDirectory.Path != "." && !projection.Path.StartsWith(projectDirectory.Path + "/", StringComparison.Ordinal))
            return new(null, SqlServerCompilationScope.LinkedGap);
        return SqlServerSchemaEvidence.PathSafe(projection.Path) ? new(projection.Path, null) : new(null, SqlServerCompilationScope.PathGap);
    }
}
