    [Fact]
    public async Task Vb_scan_artifacts_stay_public_safe()
    {
        using var temp = new TempDirectory();
        var repo = Path.Combine(temp.Path, "repo");
        Directory.CreateDirectory(repo);
        File.WriteAllText(Path.Combine(repo, "Secrets.vbproj"), """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <RootNamespace>Secrets</RootNamespace>
              </PropertyGroup>
            </Project>
            """);
        File.WriteAllText(Path.Combine(repo, "Secrets.vb"), """
            Module Secrets
                Const AccessToken As String = "vb-private-value-sentinel"
                Sub Main()
                    System.Console.WriteLine(AccessToken)
                    Dim deferred = Sub() System.Console.WriteLine(AccessToken)
                    deferred()
                End Sub
            End Module
            """);
        // A parse-broken file whose unique identifier would leak through raw
        // compiler diagnostic text if messages were not sanitized.
        File.WriteAllText(Path.Combine(repo, "Broken.vb"), """
            Module Broken
                Sub DefinitelyBroken() UniqueSyntaxMarkerName
            End Module
            """);
        Commit(repo);

        var outputPath = Path.Combine(temp.Path, "out");
        using var output = new StringWriter();
        using var error = new StringWriter();
        Assert.Equal(0, await TraceMap.Cli.TraceMapCommand.RunAsync(
            ["scan", "--repo", repo, "--out", outputPath], output, error));

        foreach (var artifact in new[]
                 {
                     Path.Combine(outputPath, "scan-manifest.json"),
                     Path.Combine(outputPath, "facts.ndjson"),
                     Path.Combine(outputPath, "report.md"),
                     Path.Combine(outputPath, "logs", "analyzer.log")
                 })
        {
            var content = await File.ReadAllTextAsync(artifact);
            Assert.DoesNotContain(temp.Path, content, StringComparison.OrdinalIgnoreCase);
            Assert.DoesNotContain("vb-private-value-sentinel", content, StringComparison.Ordinal);
            Assert.DoesNotContain("UniqueSyntaxMarkerName", content, StringComparison.Ordinal);
        }
    }

    // ---------- Symbol identity stability ----------

    [Fact]
    public void Vb_symbol_identities_are_stable_across_fact_families_and_constructs()
    {
        using var temp = new TempDirectory();
        var repo = Path.Combine(temp.Path, "repo");
        Directory.CreateDirectory(repo);
        File.WriteAllText(Path.Combine(repo, "Identity.vbproj"), """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <RootNamespace>Identity</RootNamespace>
              </PropertyGroup>
            </Project>
            """);
        File.WriteAllText(Path.Combine(repo, "Shapes.vb"), """
            Namespace Identity
                Public Interface IMemberSource
                    Function Fetch(id As Integer) As String
                End Interface

                Public Module GlobalCounters
                    Public Property Total As Integer = 0
                    Public Sub Bump(amount As Integer)
                        Total += amount
                    End Sub
                End Module

                Public Class Registry
                    Private ReadOnly _entries As New Dictionary(Of Integer, String)()
                    Public Sub New()
                        _entries(0) = "empty"
                    End Sub
                    Public Sub New(seed As Integer)
                        Me.New()
                    End Sub
                    Public Default ReadOnly Property Item(index As Integer) As String
                        Get
                            Return _entries(index)
                        End Get
                    End Property
                    Public Overridable Function Describe() As String
                        Return "registry"
                    End Function
                End Class

                Public Class AuditedRegistry
                    Inherits Registry
                    Implements IMemberSource
                    Public Overrides Function Describe() As String
                        Return "audited"
                    End Function
                    Public Function Fetch(id As Integer) As String Implements IMemberSource.Fetch
                        Dim mirror As New Registry()
                        Dim other As New Registry(7)
                        GlobalCounters.Bump(amount:=1)
                        Return Me(id) & mirror.Describe() & other.Describe()
                    End Function
                    Public Sub Copy(target As String, ParamArray tags As String())
                    End Sub
                End Class
            End Namespace
            """);
        Commit(repo);

        var result = ScanEngine.Scan(new ScanOptions(repo, Path.Combine(temp.Path, "out")));
        var semanticFacts = result.Facts
            .Where(fact => fact.RuleId.StartsWith("vb.semantic.", StringComparison.Ordinal))
            .ToArray();

        string PropertyOf(CodeFact fact, string key) => fact.Properties.TryGetValue(key, out var value) ? value : string.Empty;
        string IdOf(CodeFact fact, string prefix) => PropertyOf(fact, $"{prefix}SymbolId");

        // Module member: declared once, invoked through the module-qualified
        // name, and both fact families resolve the same method identity.
        var bumpDeclared = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.MethodDeclared
            && fact.ContractElement == "Bump");
        var bumpInvoked = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.MethodInvoked
            && fact.ContractElement == "Bump");
        Assert.Equal(IdOf(bumpDeclared, "target"), IdOf(bumpInvoked, "target"));
        Assert.Contains("GlobalCounters", IdOf(bumpDeclared, "target"), StringComparison.Ordinal);

        // Named argument binds to the resolved parameter identity.
        var bumpArgument = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.ArgumentPassed
            && fact.ContractElement == "amount");
        Assert.Equal("0", PropertyOf(bumpArgument, "parameterOrdinal"));
        Assert.Equal("Literal", PropertyOf(bumpArgument, "argumentExpressionKind"));

        // Default property: the indexed access Me(id) resolves to the same
        // identity as the Item declaration. Dictionary indexer accesses in the
        // same file are distinct identities and are not confused with it.
        var itemDeclared = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.PropertyDeclared
            && fact.ContractElement == "Item"
            && PropertyOf(fact, "isDefault") == "True"
            && fact.TargetSymbol!.Contains("Registry.Item", StringComparison.Ordinal));
        var itemAccessed = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.PropertyAccessed
            && fact.ContractElement == "Item"
            && PropertyOf(fact, "isDefault") == "True"
            && fact.TargetSymbol!.Contains("Registry.Item", StringComparison.Ordinal));
        Assert.Equal(IdOf(itemDeclared, "target"), IdOf(itemAccessed, "target"));

        // Constructor identities use the .ctor metadata name and the object
        // creation and its constructor call edge agree on that identity.
        var creations = semanticFacts
            .Where(fact => fact.FactType == FactTypes.ObjectCreated
                && PropertyOf(fact, "createdTypeName") == "Registry")
            .ToArray();
        Assert.Equal(2, creations.Length);
        Assert.All(creations, creation =>
            Assert.Contains(".ctor", PropertyOf(creation, "constructorSymbolId"), StringComparison.Ordinal));
        var creationCallEdges = semanticFacts
            .Where(fact => fact.FactType == FactTypes.CallEdge
                && PropertyOf(fact, "callKind") == "SemanticObjectCreation"
                && PropertyOf(fact, "calleeName") == "Registry")
            .ToArray();
        Assert.Equal(2, creationCallEdges.Length);
        Assert.Equal(
            creations.Select(creation => PropertyOf(creation, "constructorSymbolId")).OrderBy(value => value).ToArray(),
            creationCallEdges.Select(edge => IdOf(edge, "target")).OrderBy(value => value).ToArray());

        // Override relationship: the overriding method's declared identity is
        // the relationship source; the base method's declared identity is the
        // relationship target.
        var describeOverride = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.SymbolRelationship
            && PropertyOf(fact, "relationshipKind") == "Overrides"
            && PropertyOf(fact, "sourceSymbolKind") == "Method");
        var auditedDescribe = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.MethodDeclared
            && PropertyOf(fact, "containingType").EndsWith("AuditedRegistry", StringComparison.Ordinal)
            && fact.ContractElement == "Describe");
        var baseDescribe = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.MethodDeclared
            && PropertyOf(fact, "containingType").EndsWith("Registry", StringComparison.Ordinal)
            && fact.ContractElement == "Describe"
            && PropertyOf(fact, "containingType").Contains("Audited", StringComparison.Ordinal) == false);
        Assert.Equal(IdOf(auditedDescribe, "target"), IdOf(describeOverride, "source"));
        Assert.Equal(IdOf(baseDescribe, "target"), IdOf(describeOverride, "target"));

        // Interface member implementation: the relationship target identity is
        // the declared interface method's identity.
        var fetchImplementation = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.SymbolRelationship
            && PropertyOf(fact, "relationshipKind") == "ImplementsInterfaceMember");
        var interfaceFetch = Assert.Single(semanticFacts, fact =>
            fact.FactType == FactTypes.MethodDeclared
            && PropertyOf(fact, "containingType").EndsWith("IMemberSource", StringComparison.Ordinal)
            && fact.ContractElement == "Fetch");
        Assert.Equal(IdOf(interfaceFetch, "target"), IdOf(fetchImplementation, "target"));

        // ByRef/ParamArray parameters keep one stable declared identity per
        // parameter, and no fact family mints a second one.
        var declaredParameterIds = semanticFacts
            .Where(fact => fact.FactType == FactTypes.ParameterDeclared)
            .Select(fact => IdOf(fact, "target"))
            .ToArray();
        Assert.All(semanticFacts.Where(fact => PropertyOf(fact, "parameterSymbolId").Length > 0), fact =>
            Assert.Contains(PropertyOf(fact, "parameterSymbolId"), declaredParameterIds));
    }

    [Fact]
    public void Vb_lambda_call_sites_keep_scans_running_and_bounded_caller_text()
    {
        using var temp = new TempDirectory();
        var repo = Path.Combine(temp.Path, "repo");
        Directory.CreateDirectory(repo);
        File.WriteAllText(Path.Combine(repo, "Deferred.vbproj"), """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <RootNamespace>Deferred</RootNamespace>
              </PropertyGroup>
            </Project>
            """);
        File.WriteAllText(Path.Combine(repo, "Deferred.vb"), """
            Namespace Deferred
                Public Class Runner
                    Public Sub Run()
                        Dim deferred = Sub() System.Console.WriteLine("unused")
                        deferred()
                    End Sub
                End Class
            End Namespace
            """);
        Commit(repo);

        // Regression: VB anonymous-method caller display text must not break
        // shared downstream fact indexing (it previously crashed the WebForms
        // direct-evidence index on symbol text shaped "()").
        var result = ScanEngine.Scan(new ScanOptions(repo, Path.Combine(temp.Path, "out")));

        var lambdaCall = Assert.Single(result.Facts, fact =>
            fact.FactType == FactTypes.MethodInvoked
            && fact.ContractElement == "WriteLine"
            && fact.Evidence.FilePath == "Deferred.vb");
        Assert.Equal(EvidenceTiers.Tier1Semantic, lambdaCall.EvidenceTier);
        // The caller text is the anonymous-method display; it must stay
        // bounded and must never be mistaken for a resolvable member name.
        Assert.False(string.IsNullOrWhiteSpace(lambdaCall.SourceSymbol));
        Assert.True(lambdaCall.SourceSymbol!.Length <= 256);
    }

    // ---------- Helpers ----------

    private static void Commit(string repo, string message = "vb validation matrix fixture")
    {
        RunGit(repo, "init");
        RunGit(repo, "add", "-A");
        RunGit(repo, "-c", "user.name=TraceMap", "-c", "user.email=tests@example.invalid", "commit", "-m", message, "--allow-empty");
    }

    private static void RunGit(string repo, params string[] arguments)
    {
        using var process = new System.Diagnostics.Process
        {
            StartInfo = new System.Diagnostics.ProcessStartInfo
            {
                FileName = "git",
                WorkingDirectory = repo,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false
            }
        };
        foreach (var argument in arguments)
        {
            process.StartInfo.ArgumentList.Add(argument);
        }

        process.Start();
        process.WaitForExit(30_000);
        Assert.Equal(0, process.ExitCode);
    }

    private static string FindRepoRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null)
        {
            if (Directory.Exists(Path.Combine(directory.FullName, ".git"))
                && Directory.Exists(Path.Combine(directory.FullName, "samples")))
            {
                return directory.FullName;
            }

            directory = directory.Parent;
        }

        throw new DirectoryNotFoundException("Repository root not found.");
    }
