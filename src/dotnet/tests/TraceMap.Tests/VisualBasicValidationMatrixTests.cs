    // ---------- Generated and designer sources ----------

    [Fact]
    public void Designer_and_generated_vb_files_are_never_analyzed_or_fallback_scanned()
    {
        using var temp = new TempDirectory();
        var repo = Path.Combine(temp.Path, "repo");
        Directory.CreateDirectory(repo);
        File.WriteAllText(Path.Combine(repo, "Widget.vbproj"), """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <RootNamespace>Widget</RootNamespace>
              </PropertyGroup>
            </Project>
            """);
        // The .g/.designer/header-generated files stay inside the default SDK
        // compilation glob (they must remain protected compilation inputs), but
        // neither semantic analysis nor syntax fallback may emit evidence for
        // them.
        File.WriteAllText(Path.Combine(repo, "Live.vb"), """
            Namespace Widget
                Public Class Live
                    Public Function Name() As String
                        Return "unused"
                    End Function
                End Class
            End Namespace
            """);
        File.WriteAllText(Path.Combine(repo, "Live.designer.vb"), """
            Namespace Widget
                Partial Public Class Live
                    Private components As System.ComponentModel.IContainer
                End Class
            End Namespace
            """);
        File.WriteAllText(Path.Combine(repo, "Tooling.g.vb"), """
            Namespace Widget
                Public Class ToolingGenerated
                End Class
            End Namespace
            """);
        File.WriteAllText(Path.Combine(repo, "AssemblyInfo.vb"), """
            Namespace Widget
                Public Class AssemblyInfoShouldBeSkipped
                End Class
            End Namespace
            """);
        File.WriteAllText(Path.Combine(repo, "HeaderGenerated.vb"), """
            ' <auto-generated>
            ' Code generated by a tool; changes may be lost.
            ' </auto-generated>
            Namespace Widget
                Public Class HeaderGenerated
                End Class
            End Namespace
            """);
        Commit(repo);

        var result = ScanEngine.Scan(new ScanOptions(repo, Path.Combine(temp.Path, "out")));

        // The ordinary file is compiler-resolved exactly once. The designer and
        // SDK-generated files are skipped by the documented filename-convention
        // boundary; the auto-generated-header file keeps compiler-resolved
        // analysis like its C# counterpart (its header only gates the syntax
        // fallback, which it never reaches here).
        Assert.Contains(result.Facts, fact =>
            fact.FactType == FactTypes.TypeDeclared
            && fact.RuleId == RuleIds.VisualBasicSemanticDeclarations
            && fact.Evidence.FilePath == "Live.vb");
        Assert.Contains(result.Facts, fact =>
            fact.FactType == FactTypes.TypeDeclared
            && fact.RuleId == RuleIds.VisualBasicSemanticDeclarations
            && fact.Evidence.FilePath == "HeaderGenerated.vb");
        foreach (var generatedPath in new[] { "Live.designer.vb", "Tooling.g.vb", "AssemblyInfo.vb" })
        {
            Assert.DoesNotContain(result.Facts, fact =>
                fact.Evidence.FilePath == generatedPath
                && (fact.RuleId.StartsWith("vb.semantic.", StringComparison.Ordinal)
                    || fact.RuleId.StartsWith("vb.syntax.", StringComparison.Ordinal)));
        }

        // A generated-shape file is still a protected semantic input: mutating
        // it after snapshot capture must fail verification loudly even though
        // it never contributes evidence.
        var inventory = FileInventory.Collect(repo);
        var baseline = ScanEngine.CaptureSemanticInputSnapshot(repo, inventory);
        foreach (var generatedPath in new[] { "Live.designer.vb", "Tooling.g.vb", "HeaderGenerated.vb" })
        {
            Assert.Contains(generatedPath, baseline.Keys);
        }

        File.WriteAllText(Path.Combine(repo, "Live.designer.vb"), """
            Namespace Widget
                Partial Public Class Live
                    Private mutated As Boolean
                End Class
            End Namespace
            """);
        var semanticResult = new SemanticExtractionResult(
            [],
            [],
            true,
            false,
            new HashSet<string>(StringComparer.Ordinal),
            CompilationInputFiles: new HashSet<string>(StringComparer.Ordinal) { "Live.designer.vb" });
        Assert.Throws<SourceSnapshotException>(() =>
            ScanEngine.VerifySemanticInputSnapshot(repo, inventory, semanticResult, baseline));
    }

    // ---------- Source mutation during a live scan ----------

    [Fact]
    public void Vb_source_mutated_during_the_scan_sequence_fails_with_the_typed_snapshot_error()
    {
        using var temp = new TempDirectory();
        var repo = Path.Combine(temp.Path, "repo");
        Directory.CreateDirectory(repo);
        File.WriteAllText(Path.Combine(repo, "Mutated.vbproj"), """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <RootNamespace>Mutated</RootNamespace>
              </PropertyGroup>
            </Project>
            """);
        const string sourceRelativePath = "Live.vb";
        File.WriteAllText(Path.Combine(repo, sourceRelativePath), """
            Namespace Mutated
                Public Class Live
                    Public Sub Go()
                    End Sub
                End Class
            End Namespace
            """);
        Commit(repo);

        // This mirrors the production ScanEngine sequence: capture the
        // semantic-input snapshot, run Visual Basic semantic extraction over
        // the sources, then verify the snapshot before any fact is published.
        var inventory = FileInventory.Collect(repo);
        var baseline = ScanEngine.CaptureSemanticInputSnapshot(repo, inventory);
        var extraction = VisualBasicSemanticExtractor.Extract(
            repo,
            inventory,
            new ScanOptions(repo, Path.Combine(temp.Path, "out")));
        Assert.NotNull(extraction.AnalyzedFiles);
        Assert.Contains(sourceRelativePath, extraction.AnalyzedFiles!);

        // The mutation happens after extraction observed the source, inside
        // the protected window before publication.
        File.WriteAllText(Path.Combine(repo, sourceRelativePath), """
            Namespace Mutated
                Public Class Live
                    Public Sub Gone()
                    End Sub
                End Class
            End Namespace
            """);

        Assert.Throws<SourceSnapshotException>(() =>
            ScanEngine.VerifySemanticInputSnapshot(repo, inventory, extraction, baseline));
    }

    // ---------- Per-file semantic/syntax-fallback boundary ----------

    [Fact]
    public void Fallback_boundary_is_per_file_not_per_scan()
    {
        using var temp = new TempDirectory();
        var repo = Path.Combine(temp.Path, "repo");
        Directory.CreateDirectory(repo);
        File.WriteAllText(Path.Combine(repo, "Clean.vbproj"), """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <RootNamespace>Clean</RootNamespace>
              </PropertyGroup>
              <ItemGroup>
                <Compile Remove="Orphan.vb" />
              </ItemGroup>
            </Project>
            """);
        File.WriteAllText(Path.Combine(repo, "Compiled.vb"), """
            Namespace Clean
                Public Class Compiled
                    Public Sub Go()
                    End Sub
                End Class
            End Namespace
            """);
        // Not included in the project: reachable only through per-file fallback.
        File.WriteAllText(Path.Combine(repo, "Orphan.vb"), """
            Namespace Orphan
                Public Class Orphaned
                    Public Function Build() As String
                        Dim made As New Orphaned()
                        Return made.ToString()
                    End Function
                End Class
            End Namespace
            """);
        Commit(repo);

        var result = ScanEngine.Scan(new ScanOptions(repo, Path.Combine(temp.Path, "out")));

        // The compiled file keeps Tier1-only coverage.
        Assert.Contains(result.Facts, fact =>
            fact.FactType == FactTypes.TypeDeclared
            && fact.RuleId == RuleIds.VisualBasicSemanticDeclarations
            && fact.Evidence.FilePath == "Compiled.vb");
        Assert.DoesNotContain(result.Facts, fact =>
            fact.Evidence.FilePath == "Compiled.vb"
            && fact.RuleId.StartsWith("vb.syntax.", StringComparison.Ordinal));
        Assert.DoesNotContain(result.Facts, fact =>
            fact.FactType == FactTypes.AnalysisGap
            && fact.Evidence.FilePath == "Compiled.vb"
            && fact.Properties.GetValueOrDefault("gapKind") == "SemanticAnalysisUnavailable");

        // The orphan file keeps Tier3-only coverage with its explicit gap.
        Assert.Contains(result.Facts, fact =>
            fact.FactType == FactTypes.TypeDeclared
            && fact.RuleId == RuleIds.VisualBasicSyntaxDeclarations
            && fact.EvidenceTier == EvidenceTiers.Tier3SyntaxOrTextual
            && fact.Evidence.FilePath == "Orphan.vb");
        var unavailableGap = Assert.Single(result.Facts, fact =>
            fact.FactType == FactTypes.AnalysisGap
            && fact.Properties.GetValueOrDefault("gapKind") == "SemanticAnalysisUnavailable");
        Assert.Equal("Orphan.vb", unavailableGap.Evidence.FilePath);
    }

    // ---------- Reduced coverage honesty and sanitized gaps ----------

    [Fact]
    public void Reduced_vb_scan_reports_sanitized_gaps_with_safe_diagnostic_ids()
    {
        var repoRoot = FindRepoRoot();
        var result = ScanEngine.Scan(new ScanOptions(
            Path.Combine(repoRoot, "samples", "vb-legacy-sample"),
            Path.Combine(Path.GetTempPath(), "tracemap-vb-matrix-reduced")));

        Assert.Equal("FailedOrPartial", result.Manifest.BuildStatus);
        Assert.EndsWith("Reduced", result.Manifest.AnalysisLevel, StringComparison.Ordinal);

        var workspaceGaps = result.Facts
            .Where(fact => fact.FactType == FactTypes.AnalysisGap
                && fact.RuleId == RuleIds.VisualBasicSemanticWorkspace)
            .ToArray();
        Assert.NotEmpty(workspaceGaps);

        // Every gap message is the stable category text: no source-derived
        // text, no file paths, no raw compiler message content.
        foreach (var gap in workspaceGaps)
        {
            var message = gap.Properties["message"];
            if (gap.Properties.GetValueOrDefault("gapKind") is "CompilationDiagnostic" or "WorkspaceDiagnostic")
            {
                Assert.True(
                    message.StartsWith("Compiler diagnostic category: ", StringComparison.Ordinal)
                    || message.StartsWith("Workspace diagnostic category: ", StringComparison.Ordinal),
                    $"Unexpected unsanitized gap message: {message}");
            }

            Assert.DoesNotContain('/', message);
            Assert.DoesNotContain('\\', message);
            Assert.DoesNotContain(".vb", message, StringComparison.Ordinal);
            Assert.Equal("category-only", gap.Properties["sanitization"]);
            Assert.True(gap.Properties["messageHash"].Length > 0);
        }

        // Compiler-diagnostic gaps carry the bounded Visual Basic diagnostic
        // id (BCxxxxx), never the raw message.
        var compilationGaps = workspaceGaps
            .Where(fact => fact.Properties.GetValueOrDefault("gapKind") == "CompilationDiagnostic")
            .ToArray();
        Assert.NotEmpty(compilationGaps);
        Assert.All(compilationGaps, gap =>
            Assert.Matches(@"^BC[0-9]{5}$", gap.Properties["diagnosticId"]));

        // The legacy fixture is only partially bound: its readable files keep
        // partial Tier1 evidence and must not receive Tier3 duplicates.
        var tier1Files = result.Facts
            .Where(fact => fact.EvidenceTier == EvidenceTiers.Tier1Semantic)
            .Select(fact => fact.Evidence.FilePath)
            .Distinct(StringComparer.Ordinal)
            .ToHashSet(StringComparer.Ordinal);
        Assert.Superset(
            tier1Files,
            new HashSet<string>(StringComparer.Ordinal) { "CatalogModels.vb", "CatalogService.vb", "LegacyQueueBridge.vb" });
        Assert.DoesNotContain(result.Facts, fact =>
            fact.RuleId == RuleIds.VisualBasicSyntaxDeclarations
            || fact.RuleId == RuleIds.VisualBasicSyntaxMemberAccess
            || fact.RuleId == RuleIds.VisualBasicSyntaxObjectCreation);
        Assert.DoesNotContain(result.Facts, fact =>
            fact.FactType == FactTypes.AnalysisGap
            && fact.Properties.GetValueOrDefault("gapKind") == "SemanticAnalysisUnavailable"
            && tier1Files.Contains(fact.Evidence.FilePath));
    }

